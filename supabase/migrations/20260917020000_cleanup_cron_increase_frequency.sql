-- 日次クリーンアップの処理能力不足を解消（2026-09-17）。
--
-- 「DB容量が500MB上限を超過している、cleanupは正常に動いているか」というユーザー指摘への対応。
-- 調査結果: cleanup_low_view_clips()自体は毎日正常に実行されている（cron.job_run_details・
-- clip_cleanup_logともに直近まで連続成功を確認）。削除条件（14日超過かつ視聴回数50回未満、
-- 「日次クリーンアップ」節参照）も変更していない。
--
-- 問題は処理能力側: 追跡配信者数が2026-09-07時点の5,884件から本番実測で8,634件まで
-- さらに増加し、新規クリップの流入が実測38,724件/日に達していた（2026-09-07時点の
-- 「実質1万件/日規模」からさらに約4倍）。1日1回・p_batch_size=15000（20260907020000で設定）
-- では追いつかず、削除対象の未処理バックログが本番実測で52,657件まで積み上がっていた
-- （DB容量701MB、うちclipsテーブルが586MB）。
--
-- 対応: 削除条件・削除バッチサイズ自体は変更せず（1回の呼び出しが長くなりすぎると
-- daily_ranking_posts外部キー制約のチェックコストでservice_roleのstatement_timeout(300s)に
-- 近づくリスクがある、20260904080000_clip_cleanup_batched.sql参照）、実行頻度を1日1回から
-- 4時間おき（1日6回、最大90,000件/日の処理能力）に増やすことで、既存バックログの解消と
-- 今後の流入ペースへの追従の両方に対応する。
--
-- **今後の教訓**: 追跡配信者数の増加ペースが今回のように短期間で数倍になるケースでは、
-- クリーンアップの処理能力もそれに応じて見直しが必要になる。DB容量・clip_cleanup_logの
-- deleted_countが連日p_batch_size上限に張り付いている（＝バックログが捌けきれていない兆候）
-- 場合は、条件を緩める（grace_period_days短縮・view_threshold引き上げ）前に、まず頻度/
-- バッチサイズという「処理能力」側のパラメータを疑うこと（削除対象の定義＝ユーザーと合意した
-- ポリシーそのものは安易に変えない）。
select cron.unschedule('trigger-cleanup-low-view-clips');

select cron.schedule(
  'trigger-cleanup-low-view-clips',
  '0 */4 * * *',
  $$
  select cleanup_low_view_clips(14, 50, 15000);
  $$
);
