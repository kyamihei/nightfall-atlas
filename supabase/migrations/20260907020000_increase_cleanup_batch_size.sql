-- 日次クリーンアップの処理件数不足を解消（2026-09-07）。
--
-- 「ストレージ上限超過とcleanup cronの機能不全を修正」節の対応でDB容量を403MBまで戻したが、
-- その後わずか半日ほどで536MBまで再肥大化する事象が発生。調査したところ、追跡配信者数が
-- 2026-09-03時点の約1,900件から5,884件（3倍以上）に増えており、sync-twitch-clips.tsが
-- 新規発見のたびに行う「配信者の過去クリップ一括バックフィル」により、直近24時間だけで
-- 10,112件のclipsが新規挿入されていた（うち6,180件は挿入時点で既に14日超過＝ほぼ即座に
-- クリーンアップ対象になりうる古いクリップ）ことが判明した。
--
-- cronジョブ（trigger-cleanup-low-view-clips）は引数無しでcleanup_low_view_clips()を呼んでおり
-- デフォルトのp_batch_size=2000件/日だったため、この流入ペース（実質1万件/日規模）に
-- 全く追いついていなかった。関数のデフォルト値自体は変更せず（手動でのアドホック実行時の
-- 挙動を変えないため）、cronジョブの呼び出しだけ明示的にp_batch_size=15000へ引き上げる。
select cron.schedule(
  'trigger-cleanup-low-view-clips',
  '0 18 * * *',
  $$
  select cleanup_low_view_clips(14, 50, 15000);
  select refresh_ranking_views();
  $$
);
